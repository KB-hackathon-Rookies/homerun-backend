-- FCT-101 이 은행별 금리를 note 자유텍스트 한 줄에 묻어 두고 있다.
--
--   FCT-101  은행 전세대출 평균금리  전체 평균 3.75%
--   note: 토스 3.34 · KB 3.39 · 케이 3.65 · NH 3.67 · 하나 3.72 · 신한 3.86 · 카카오 3.87 · 우리 3.87
--
-- 은행별 비교(POL-03-07)를 하려면 값을 하나씩 읽어야 하는데, note 를 런타임에 파싱하면
-- 문자열이 조금만 바뀌어도 조용히 틀린 금리를 보여주게 된다. V18 이 열람·발급 수수료를
-- 갈라 놓은 것과 같이, 은행별 행을 따로 세운다.
--
-- 기존 값을 지우지 않는다. FCT-101 의 3.75% 는 여전히 맞다 -- 다만 그것이 무엇의 값인지가
-- 아래 두 가지 이유로 분명해야 한다.
--
-- 1) 3.75% 는 나열된 8개 은행의 산술평균이 아니다. 8개 평균은 3.671 이다. 3.75 는 은행연합회가
--    공시한 전체 평균이라 집계 대상 은행이 다르다. 응답에서 평균을 다시 계산하면 두 값이
--    갈라진다. 전체 평균이 필요하면 FCT-101 을 그대로 읽는다.
--
-- 2) change_cycle 이 '주간' 인데 effective_from 이 2026-01-01 이다. 주 단위로 바뀌는 값이
--    그만큼 묵었다. 그래서 은행별 행은 REVIEW 로 넣어 화면에 "변경 가능" 이 실리게 한다.
--    effective_from 도 오늘이 아니라 원본과 같은 날짜로 둔다 -- 오늘로 적으면 오늘 확인한
--    값처럼 보인다.

INSERT INTO config_effective
  (fact_code, category, item, value_text, value_num, unit, apply_condition, source,
   confidence, change_cycle, related_feature, note, effective_from, updated_by)
SELECT code, '금리', item, description, value, '%',
  '은행연합회 공시 신규취급 평균. 광고금리가 아니다(FCT-102)', '은행연합회',
  'REVIEW', '주간', 'POL-03',
  'FCT-101 의 note 를 은행별로 분리한 값이다. 주간 공시라 재확인이 필요하다',
  DATE '2026-01-01', 'fact-registry'
FROM (VALUES
  ('FCT-201', '토스뱅크 전세대출 평균금리', '토스뱅크 연 3.34%', 3.34),
  ('FCT-202', 'KB국민은행 전세대출 평균금리', 'KB국민은행 연 3.39%', 3.39),
  ('FCT-203', '케이뱅크 전세대출 평균금리', '케이뱅크 연 3.65%', 3.65),
  ('FCT-204', 'NH농협은행 전세대출 평균금리', 'NH농협은행 연 3.67%', 3.67),
  ('FCT-205', '하나은행 전세대출 평균금리', '하나은행 연 3.72%', 3.72),
  ('FCT-206', '신한은행 전세대출 평균금리', '신한은행 연 3.86%', 3.86),
  ('FCT-207', '카카오뱅크 전세대출 평균금리', '카카오뱅크 연 3.87%', 3.87),
  ('FCT-208', '우리은행 전세대출 평균금리', '우리은행 연 3.87%', 3.87)
) AS facts(code, item, description, value);

-- 원본 note 는 이제 갈라진 곳을 가리킨다. 값이 두 군데 남아 갈라지지 않게 한다.
UPDATE config_effective
SET item = '은행 전세대출 공시 전체 평균금리',
    note = '은행별 값은 FCT-201~208 로 분리했다. 이 값은 공시 전체 평균이라 8개 은행의 산술평균(3.671)과 다르다'
WHERE fact_code = 'FCT-101';
