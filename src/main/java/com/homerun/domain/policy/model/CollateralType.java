package com.homerun.domain.policy.model;

/**
 * 일반 전세대출의 담보(보증) 방식(BR-19). 은행이 정하지만, 방식마다 한도 공식이 달라 세 가지를
 * 모두 계산해 보여준다.
 *
 * <p>채권양도는 임대인이 공공기관일 때만 쓰는 방식이라 여기 두지 않는다 — 사전 필터가 붙는
 * 별개 경로다(FR-P5-06). 여기는 사용자가 상담에서 받을 수 있는 세 보증기관만 담는다.
 */
public enum CollateralType {
    /** HF 주신보. 사람 기준(소득·재직·신용). 증빙소득 3.5배 이내. */
    HF,
    /** HUG 안심전세. 집 기준(시세). 만 34세 이하·신혼은 보증금 90%까지. */
    HUG,
    /** SGI 서신보. 한도가 가장 크지만 보증료도 비싸다. */
    SGI
}
